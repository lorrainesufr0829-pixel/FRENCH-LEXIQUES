-- LEXIQUE: many-to-many vocabulary categorization
-- Keeps vocabulary.category and vocabulary.level for backward compatibility.
-- Existing values are migrated into the normalized category tables.

create table if not exists public.vocabulary_categories (
    id bigint generated by default as identity primary key,
    name text not null,
    category_type text not null default 'collection'
        check (category_type in ('collection', 'level')),
    created_at timestamptz not null default now(),
    constraint vocabulary_categories_name_type_unique unique (name, category_type)
);

create table if not exists public.vocabulary_category_links (
    vocabulary_id bigint not null
        references public.vocabulary(id) on delete cascade,
    category_id bigint not null
        references public.vocabulary_categories(id) on delete cascade,
    created_at timestamptz not null default now(),
    primary key (vocabulary_id, category_id)
);

create index if not exists idx_vocabulary_category_links_category
    on public.vocabulary_category_links(category_id);

-- Migrate the existing single category and level fields without deleting them.
insert into public.vocabulary_categories (name, category_type)
select distinct trim(category), 'collection'
from public.vocabulary
where category is not null and trim(category) <> ''
on conflict (name, category_type) do nothing;

insert into public.vocabulary_categories (name, category_type)
select distinct trim(level), 'level'
from public.vocabulary
where level is not null and trim(level) <> ''
on conflict (name, category_type) do nothing;

insert into public.vocabulary_category_links (vocabulary_id, category_id)
select v.id, c.id
from public.vocabulary v
join public.vocabulary_categories c
  on c.name = trim(v.category) and c.category_type = 'collection'
where v.category is not null and trim(v.category) <> ''
on conflict do nothing;

insert into public.vocabulary_category_links (vocabulary_id, category_id)
select v.id, c.id
from public.vocabulary v
join public.vocabulary_categories c
  on c.name = trim(v.level) and c.category_type = 'level'
where v.level is not null and trim(v.level) <> ''
on conflict do nothing;

-- The current LEXIQUE frontend uses the Supabase anon key without user auth.
-- These policies mirror the existing public vocabulary-table access model.
alter table public.vocabulary_categories enable row level security;
alter table public.vocabulary_category_links enable row level security;

grant select, insert, update, delete on public.vocabulary_categories to anon, authenticated;
grant select, insert, update, delete on public.vocabulary_category_links to anon, authenticated;
grant usage, select on sequence public.vocabulary_categories_id_seq to anon, authenticated;

drop policy if exists "LEXIQUE categories are readable" on public.vocabulary_categories;
create policy "LEXIQUE categories are readable"
on public.vocabulary_categories for select to anon, authenticated using (true);

drop policy if exists "LEXIQUE categories are insertable" on public.vocabulary_categories;
create policy "LEXIQUE categories are insertable"
on public.vocabulary_categories for insert to anon, authenticated with check (true);

drop policy if exists "LEXIQUE categories are updatable" on public.vocabulary_categories;
create policy "LEXIQUE categories are updatable"
on public.vocabulary_categories for update to anon, authenticated using (true) with check (true);

drop policy if exists "LEXIQUE categories are deletable" on public.vocabulary_categories;
create policy "LEXIQUE categories are deletable"
on public.vocabulary_categories for delete to anon, authenticated using (true);

drop policy if exists "LEXIQUE category links are readable" on public.vocabulary_category_links;
create policy "LEXIQUE category links are readable"
on public.vocabulary_category_links for select to anon, authenticated using (true);

drop policy if exists "LEXIQUE category links are insertable" on public.vocabulary_category_links;
create policy "LEXIQUE category links are insertable"
on public.vocabulary_category_links for insert to anon, authenticated with check (true);

drop policy if exists "LEXIQUE category links are updatable" on public.vocabulary_category_links;
create policy "LEXIQUE category links are updatable"
on public.vocabulary_category_links for update to anon, authenticated using (true) with check (true);

drop policy if exists "LEXIQUE category links are deletable" on public.vocabulary_category_links;
create policy "LEXIQUE category links are deletable"
on public.vocabulary_category_links for delete to anon, authenticated using (true);
